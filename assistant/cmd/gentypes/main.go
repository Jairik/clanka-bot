// Command gentypes generates the Dashboard's TypeScript view types from the
// Go view structs in internal/dashboard. Run it after changing a view struct:
//
//	cd assistant && go run ./cmd/gentypes
//
// The web types are the contract between the Go handlers and the React app, so
// they are generated rather than hand-mirrored: a renamed Go field must change
// the TypeScript and fail the build, not render undefined.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

// roots are the page views the app loads. They are listed explicitly so a
// renamed or deleted Go struct fails this command instead of silently
// disappearing from the bundle.
var roots = []string{
	"activityView", "alertsView", "healthView", "hermesView", "notesView",
	"personasView", "phrasebookView", "routesView", "secretsView",
	"sessionView", "settingsView", "soundsView", "spotifyView",
	"voiceSamplesView", "voicesView", "volumeView",
}

// names pins the TypeScript names the app already imports where the Go name
// would otherwise generate a different one. Everything else is the Go name
// with a trailing View removed and the first rune capitalised.
var names = map[string]string{
	"sessionView":      "Session",
	"volumeView":       "Volume",
	"settingsToolView": "SettingTool",
	"permissionChoice": "Choice",
	"voicePhraseView":  "VoiceSamplePhrase",
	"voiceTakeView":    "VoiceSampleTake",
	"voiceBundleView":  "VoiceSampleBundle",
}

func main() {
	src := flag.String("src", filepath.Join("internal", "dashboard"), "package directory with the view structs")
	out := flag.String("out", filepath.Join("web", "src", "types.ts"), "generated TypeScript file")
	flag.Parse()

	pkgs, err := parser.ParseDir(token.NewFileSet(), *src, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, parser.ParseComments)
	if err != nil {
		log.Fatalf("parse %s: %v", *src, err)
	}
	pkg, ok := pkgs["dashboard"]
	if !ok {
		log.Fatalf("%s is not package dashboard", *src)
	}

	types := map[string]*ast.TypeSpec{}
	for _, file := range pkg.Files {
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts := spec.(*ast.TypeSpec)
				if _, ok := ts.Type.(*ast.StructType); ok {
					types[ts.Name.Name] = ts
				}
			}
		}
	}
	for _, root := range roots {
		if types[root] == nil {
			log.Fatalf("root view %q is gone; update cmd/gentypes when a page view is renamed", root)
		}
	}

	// Reachable nested structs are emitted too, so a field can point at a type
	// the page does not name directly.
	reachable := map[string]bool{}
	var walk func(name string)
	walk = func(name string) {
		if reachable[name] {
			return
		}
		reachable[name] = true
		st := types[name].Type.(*ast.StructType)
		for _, field := range st.Fields.List {
			eachIdent(field.Type, func(id string) {
				if types[id] != nil {
					walk(id)
				}
			})
		}
	}
	for _, root := range roots {
		walk(root)
	}

	var ordered []string
	for name := range reachable {
		ordered = append(ordered, name)
	}
	sort.Slice(ordered, func(i, j int) bool { return tsName(ordered[i]) < tsName(ordered[j]) })

	var b bytes.Buffer
	b.WriteString("// Code generated by assistant/cmd/gentypes from internal/dashboard; DO NOT EDIT.\n")
	b.WriteString("// Run `cd assistant && go run ./cmd/gentypes` after changing a Go view struct.\n")
	b.WriteString("// Field names are the Go encoding/json defaults, so Go and TypeScript cannot drift.\n\n")
	for _, name := range ordered {
		writeType(&b, name, types[name])
	}
	b.WriteString("// Hand-written types have no Go counterpart; the generator never touches them.\n")
	b.WriteString("export * from \"./types.manual\";\n")

	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeType(b *bytes.Buffer, goName string, spec *ast.TypeSpec) {
	if spec.Doc != nil {
		b.WriteString("/**\n")
		for _, line := range strings.Split(strings.TrimSpace(spec.Doc.Text()), "\n") {
			b.WriteString(" * " + line + "\n")
		}
		b.WriteString(" */\n")
	}
	fmt.Fprintf(b, "export type %s = {\n", tsName(goName))
	st := spec.Type.(*ast.StructType)
	for _, field := range st.Fields.List {
		if name, ok := fieldName(field); ok {
			if c := field.Doc; c != nil {
				for _, line := range strings.Split(strings.TrimSpace(c.Text()), "\n") {
					fmt.Fprintf(b, "  // %s\n", line)
				}
			}
			fmt.Fprintf(b, "  %s: %s;\n", name, typeOf(field.Type))
		}
	}
	b.WriteString("};\n\n")
}

// fieldName returns the exported TypeScript name, honouring a json tag and
// dropping an unexported or json:"-" field.
func fieldName(field *ast.Field) (string, bool) {
	if len(field.Names) == 0 {
		return "", false // embedded fields have no counterpart in these views
	}
	name := field.Names[0].Name
	if !ast.IsExported(name) {
		return "", false
	}
	if field.Tag == nil {
		return name, true
	}
	tag := strings.Trim(field.Tag.Value, "`")
	const key = `json:"`
	i := strings.Index(tag, key)
	if i < 0 {
		return name, true
	}
	rest := tag[i+len(key):]
	value := rest[:strings.Index(rest, `"`)]
	if value == "-" {
		return "", false
	}
	if comma := strings.Index(value, ","); comma >= 0 {
		if value[:comma] != "" {
			return value[:comma], true
		}
		return name, true
	}
	return value, true
}

// typeOf maps a Go field type to its JSON shape. A nil slice or pointer
// marshals as null, so both carry a null in the TypeScript type.
func typeOf(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "string"
		case "bool":
			return "boolean"
		case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "float32", "float64":
			return "number"
		case "any":
			return "unknown"
		default:
			return tsName(t.Name)
		}
	case *ast.StarExpr:
		return typeOf(t.X) + " | null"
	case *ast.ArrayType:
		return typeOf(t.Elt) + "[] | null"
	case *ast.MapType:
		return "Record<" + typeOf(t.Key) + ", " + typeOf(t.Value) + ">"
	case *ast.SelectorExpr:
		// An external named type (for example tool.Permission) reaches JSON as
		// its underlying value; every one in these views is a string.
		return "string"
	case *ast.StructType:
		var b strings.Builder
		b.WriteString("{ ")
		for _, field := range t.Fields.List {
			if name, ok := fieldName(field); ok {
				fmt.Fprintf(&b, "%s: %s; ", name, typeOf(field.Type))
			}
		}
		b.WriteString("}")
		return b.String()
	case *ast.InterfaceType:
		return "unknown"
	default:
		return "unknown"
	}
}

// eachIdent visits every identifier under a type expression, so reachability
// follows slices and pointers to their element type.
func eachIdent(expr ast.Expr, visit func(string)) {
	switch t := expr.(type) {
	case *ast.Ident:
		visit(t.Name)
	case *ast.StarExpr:
		eachIdent(t.X, visit)
	case *ast.ArrayType:
		eachIdent(t.Elt, visit)
	case *ast.MapType:
		eachIdent(t.Key, visit)
		eachIdent(t.Value, visit)
	case *ast.StructType:
		for _, field := range t.Fields.List {
			eachIdent(field.Type, visit)
		}
	}
}

func isRoot(goName string) bool {
	for _, root := range roots {
		if root == goName {
			return true
		}
	}
	return false
}

// tsName is the TypeScript name for a Go struct.
func tsName(goName string) string {
	if pinned, ok := names[goName]; ok {
		return pinned
	}
	// Page views keep their View suffix: the app imports ActivityView,
	// SettingsView and so on. Nested views drop it (requestView -> Request).
	name := goName
	if !isRoot(goName) {
		name = strings.TrimSuffix(name, "View")
	}
	runes := []rune(name)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}
